// sitemap.xml and robots.txt are generated rather than stored, so a domain move
// (SITE_URL) rewrites every URL on the site in one deploy, and the document list
// can never drift out of sync with what the app can actually build.

const { STAGES } = require('./templates');
const { siteOrigin } = require('./site');

// Bump this when a landing page's copy actually changes. Every /doc/* page and
// the shell it renders from move together, so they share one date; a lastmod
// that advances on every deploy teaches Google to ignore the signal.
const CONTENT_UPDATED = '2026-11-10';

// Highest-intent documents get the higher priority. Google ignores priority, but
// other engines and human audits still read it, and it documents intent.
const PUSHED = new Set(['cv', 'cover_letter', 'job_application', 'admission_application']);
const NEXT = new Set(['resignation']);

function docKeys() {
  const keys = [];
  for (const stage of Object.values(STAGES)) keys.push(...Object.keys(stage.documents));
  return keys;
}

// Ordered most-important-first, which is also how a human would audit it.
function sitemapEntries() {
  const entries = [
    { path: '/', changefreq: 'weekly', priority: '1.0' },
    { path: '/scan', changefreq: 'weekly', priority: '0.8' },
    { path: '/tools', changefreq: 'weekly', priority: '0.8' },
  ];
  // /template is deliberately absent: without a document already chosen it
  // renders the catalog, so it duplicates "/" and competes with it for the same
  // query. It is noindex'd in server.js rather than listed here.

  for (const key of ['cv', 'cover_letter', 'job_application']) {
    if (docKeys().includes(key)) entries.push({ path: `/doc/${key}`, changefreq: 'weekly', priority: '0.9' });
  }
  for (const key of docKeys()) {
    if (['cv', 'cover_letter', 'job_application'].includes(key)) continue;
    entries.push({
      path: `/doc/${key}`,
      changefreq: PUSHED.has(key) ? 'weekly' : 'monthly',
      priority: PUSHED.has(key) ? '0.8' : NEXT.has(key) ? '0.8' : '0.7',
    });
  }

  entries.push({ path: '/about.html', changefreq: 'monthly', priority: '0.6' });
  for (const legal of ['terms', 'privacy', 'refund', 'delete-account']) {
    entries.push({ path: `/${legal}.html`, changefreq: 'yearly', priority: '0.3' });
  }
  return entries;
}

function renderSitemap(origin = siteOrigin()) {
  const urls = sitemapEntries().map((e) => (
    `  <url><loc>${origin}${e.path}</loc>`
    + `<lastmod>${CONTENT_UPDATED}</lastmod>`
    + `<changefreq>${e.changefreq}</changefreq>`
    + `<priority>${e.priority}</priority></url>`
  )).join('\n');

  return '<?xml version="1.0" encoding="UTF-8"?>\n'
    + '<!--\n'
    + '  Generated by utils/sitemap.js. lastmod is the one sitemap field Google\n'
    + '  still acts on (changefreq and priority are ignored). Bump CONTENT_UPDATED\n'
    + '  only when a page\'s content actually changes; test/brandSeo.test.js\n'
    + '  enforces that every URL carries one.\n'
    + '-->\n'
    + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
    + `${urls}\n`
    + '</urlset>\n';
}

function renderRobots(origin = siteOrigin()) {
  return [
    'User-agent: *',
    'Allow: /',
    '# /write is a personal editing/payment screen (also noindex\'d in its HTML)',
    'Disallow: /write',
    'Disallow: /api/',
    '',
    `Sitemap: ${origin}/sitemap.xml`,
    '',
  ].join('\n');
}

module.exports = { CONTENT_UPDATED, sitemapEntries, renderSitemap, renderRobots };
